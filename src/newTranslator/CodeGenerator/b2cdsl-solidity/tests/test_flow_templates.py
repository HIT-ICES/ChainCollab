"""Golden generation regressions captured before the Jinja-only skeleton refactor.

The DSL fixture is synthetic test data. Hashes cover exact output bytes,
including whitespace, as well as individual flow blocks for useful diagnostics.
Run: python -m unittest discover -s <this directory> -v
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys
from tempfile import TemporaryDirectory
import unittest

TEST_DIR = Path(__file__).resolve().parent
TRANSLATOR_ROOT = TEST_DIR.parents[2]
for package in (
    TRANSLATOR_ROOT / "CodeGenerator/b2cdsl-solidity",
    TRANSLATOR_ROOT / "CodeGenerator/b2cdsl-go",
    TRANSLATOR_ROOT / "DSL/B2CDSL",
):
    sys.path.insert(0, str(package))

import b2cdsl_go
import b2cdsl_solidity
from textx import metamodel_from_file


class FlowTemplateGoldenTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.fixture = TEST_DIR / "fixtures/flow_template_regression.b2c"
        cls.expected = json.loads(
            (TEST_DIR / "fixtures/flow_template_regression.sha256.json").read_text()
        )
        cls.metamodel = metamodel_from_file(
            str(TRANSLATOR_ROOT / "DSL/B2CDSL/b2cdsl/b2c.tx")
        )

    def model(self):
        return self.metamodel.model_from_file(str(self.fixture))

    def assert_generated_bytes(self, module, target, extension):
        with TemporaryDirectory() as folder:
            output = Path(folder) / (self.fixture.stem + extension)
            module.generator_callback(self.model(), str(output))
            self.assertEqual(
                hashlib.sha256(output.read_bytes()).hexdigest(),
                self.expected["files"][target],
                "Generated bytes differ from the pre-refactor baseline",
            )

    def test_go_full_contract_matches_pre_refactor_bytes(self):
        self.assert_generated_bytes(b2cdsl_go, "go", ".go")

    def test_solidity_full_contract_matches_pre_refactor_bytes(self):
        self.assert_generated_bytes(b2cdsl_solidity, "solidity", ".sol")

    def test_each_solidity_flow_matches_pre_refactor_bytes(self):
        adapter = b2cdsl_solidity.DSLContractAdapter(self.model().contracts[0])
        blocks = b2cdsl_solidity.SolidityRenderer(adapter).build_context()["flow_functions"]
        expected = self.expected["solidity_flow_blocks"]
        self.assertEqual(len(blocks), len(expected))
        for block, original in zip(blocks, expected):
            with self.subTest(function=original["signature"]):
                self.assertEqual(block.splitlines()[0], original["signature"])
                self.assertEqual(
                    hashlib.sha256(block.encode("utf-8")).hexdigest(),
                    original["sha256"],
                )


if __name__ == "__main__":
    unittest.main()
